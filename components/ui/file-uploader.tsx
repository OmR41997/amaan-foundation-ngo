"use client";

import { uploadFileToApi } from "@/lib/api/uploads";
import type { ImageCompressionOptions } from "@/lib/image-compressor";
import Image from "next/image";
import { useCallback, useEffect, useId, useMemo, useRef, useState } from "react";

export interface FileUploaderProps {
  /** Current uploaded media URL */
  value?: string;
  /** Callback invoked when the uploaded URL changes (or on removal with "") */
  onChange: (url: string) => void;
  /** Upload category to organize files (e.g. "gallery", "teams", "members", "general") */
  category?: string;
  /** Input field label */
  label?: string;
  /** Subtitle / helper note */
  helpText?: string;
  /** Whether the field is mandatory */
  required?: boolean;
  /** Visual presentation style */
  variant?: "admin" | "card" | "compact";
  /** Language locale for internationalized messages */
  locale?: "en" | "hi";
  /** Maximum acceptable file size before compression in Megabytes (default: 10MB) */
  maxSizeMB?: number;
  /** Accepted mime types (defaults to common image formats) */
  accept?: string;
  /** Whether the input is disabled */
  disabled?: boolean;
  /** Optional custom compression settings */
  compressionOptions?: ImageCompressionOptions;
  /** Optional callback to notify caller of the original selected File */
  onFileSelect?: (file: File | null) => void;
  /** Additional container classes */
  className?: string;
}

export function FileUploader({
  value = "",
  onChange,
  category = "general",
  label,
  helpText,
  required = false,
  variant = "admin",
  locale = "en",
  maxSizeMB = 10,
  accept = "image/jpeg,image/png,image/webp,image/gif,image/svg+xml",
  disabled = false,
  compressionOptions,
  onFileSelect,
  className = "",
}: FileUploaderProps) {
  const [uploading, setUploading] = useState(false);
  const [uploadProgress, setUploadProgress] = useState<string>("");
  const [error, setError] = useState<string | null>(null);
  const [isDragging, setIsDragging] = useState(false);
  const [copied, setCopied] = useState(false);
  const [selectedFileName, setSelectedFileName] = useState<string>("");
  const [selectedFileSize, setSelectedFileSize] = useState<number | null>(null);
  const [localPreviewUrl, setLocalPreviewUrl] = useState<string | null>(null);

  const fileInputRef = useRef<HTMLInputElement>(null);
  const inputId = useId();

  // Clean up any temporary blob URL on unmount or change
  useEffect(() => {
    return () => {
      if (localPreviewUrl && localPreviewUrl.startsWith("blob:")) {
        URL.revokeObjectURL(localPreviewUrl);
      }
    };
  }, [localPreviewUrl]);

  // Determine current active preview
  const displayUrl = useMemo(() => {
    if (localPreviewUrl) return localPreviewUrl;
    if (value) return value;
    return "";
  }, [localPreviewUrl, value]);

  // Localized string dictionary
  const t = useMemo(() => {
    if (locale === "hi") {
      return {
        label: label || "फोटो / दस्तावेज़ अपलोड",
        dragText: "फोटो यहाँ खींचें या अपलोड करने के लिए क्लिक करें",
        subText: `JPG, PNG, WEBP (अधिकतम ${maxSizeMB} MB - स्वतः संकुचित)`,
        compressing: "फोटो संकुचित की जा रही है...",
        uploading: "सर्वर पर अपलोड हो रहा है...",
        success: "अपलोड सफल!",
        changePhoto: "फोटो बदलें",
        removePhoto: "हटाएं",
        copyUrl: "URL कॉपी करें",
        copiedUrl: "कॉपी हो गया!",
        selectedFile: "चयनित फोटो",
        sizeExceeded: `फ़ाइल का आकार ${maxSizeMB}MB से अधिक नहीं होना चाहिए।`,
        invalidType: "कृपया मान्य छवि (JPG, PNG, WEBP, SVG) फ़ाइल चुनें।",
        uploadFailed: "अपलोड विफल रहा। कृपया पुन: प्रयास करें।",
        urlLabel: "अपलोड किया गया URL (API द्वारा उत्पन्न):",
      };
    }
    return {
      label: label || "Photo / Image",
      dragText: "Click or drag & drop photo here to upload",
      subText: `Supports JPG, PNG, WEBP (Max ${maxSizeMB}MB, auto-compressed)`,
      compressing: "Compressing image...",
      uploading: "Uploading to server...",
      success: "Upload successful!",
      changePhoto: "Change Photo",
      removePhoto: "Remove",
      copyUrl: "Copy URL",
      copiedUrl: "Copied URL!",
      selectedFile: "Selected Photo",
      sizeExceeded: `File size must not exceed ${maxSizeMB}MB.`,
      invalidType: "Please select a valid image file (JPEG, PNG, WEBP, SVG).",
      uploadFailed: "Upload failed. Please try again.",
      urlLabel: "Uploaded URL / path (generated by API):",
    };
  }, [locale, label, maxSizeMB]);

  const handleProcessFile = useCallback(
    async (file: File) => {
      if (!file) return;

      setError(null);

      // Validate size constraint before starting
      if (file.size > maxSizeMB * 1024 * 1024) {
        setError(t.sizeExceeded);
        return;
      }

      // Check file type if restricted to images
      if (accept.includes("image/") && !file.type.startsWith("image/")) {
        setError(t.invalidType);
        return;
      }

      // Keep file info for friendly UI display
      setSelectedFileName(file.name);
      setSelectedFileSize(file.size);
      onFileSelect?.(file);

      // Create instant local blob preview for immediate UI feedback
      if (file.type.startsWith("image/")) {
        try {
          const blobUrl = URL.createObjectURL(file);
          setLocalPreviewUrl(blobUrl);
        } catch {
          // Ignore preview generation errors
        }
      }

      setUploading(true);
      setUploadProgress(t.compressing);

      try {
        // Upload directly via backend upload API with automatic client-side compression
        const uploadedUrl = await uploadFileToApi(file, {
          category,
          title: file.name,
          compress: true,
          compressionOptions,
          onProgress: (status) => {
            if (status.includes("Compressing")) {
              setUploadProgress(t.compressing);
            } else {
              setUploadProgress(t.uploading);
            }
          },
        });

        if (!uploadedUrl) {
          throw new Error("Could not retrieve image URL from upload response.");
        }

        setUploadProgress(t.success);
        onChange(uploadedUrl);
      } catch (err: unknown) {
        const msg =
          err instanceof Error
            ? err.message
            : t.uploadFailed;
        setError(msg);
        // Reset preview if upload completely failed and no previous value
        if (!value) {
          setLocalPreviewUrl(null);
        }
      } finally {
        setUploading(false);
        if (fileInputRef.current) {
          fileInputRef.current.value = "";
        }
      }
    },
    [
      accept,
      category,
      compressionOptions,
      maxSizeMB,
      onChange,
      onFileSelect,
      t,
      value,
    ],
  );

  const handleFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      handleProcessFile(file);
    }
  };

  const handleDragOver = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    if (!disabled && !uploading) {
      setIsDragging(true);
    }
  };

  const handleDragLeave = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(false);
  };

  const handleDrop = (e: React.DragEvent) => {
    e.preventDefault();
    e.stopPropagation();
    setIsDragging(false);
    if (disabled || uploading) return;

    const droppedFile = e.dataTransfer.files?.[0];
    if (droppedFile) {
      handleProcessFile(droppedFile);
    }
  };

  const handleRemove = () => {
    if (localPreviewUrl && localPreviewUrl.startsWith("blob:")) {
      URL.revokeObjectURL(localPreviewUrl);
    }
    setLocalPreviewUrl(null);
    setSelectedFileName("");
    setSelectedFileSize(null);
    setError(null);
    setUploadProgress("");
    onChange("");
    onFileSelect?.(null);
    if (fileInputRef.current) {
      fileInputRef.current.value = "";
    }
  };

  const handleCopyUrl = async () => {
    if (!value) return;
    try {
      await navigator.clipboard.writeText(value);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Fallback or ignore
    }
  };

  const formatFileSize = (bytes: number | null) => {
    if (!bytes) return "";
    if (bytes < 1024) return `${bytes} B`;
    if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
    return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
  };

  const hasImage = Boolean(displayUrl);

  // -------------------------------------------------------------
  // RENDER: Card Variant (Public Forms & Friendly Cards)
  // -------------------------------------------------------------
  if (variant === "card") {
    return (
      <div className={`space-y-2.5 ${className}`}>
        {label ? (
          <label
            htmlFor={inputId}
            className="flex items-center justify-between text-sm font-medium text-[var(--muted,#475569)]"
          >
            <span>
              {label}
              {required ? <span className="ml-1 text-rose-500 font-bold">*</span> : null}
            </span>
            {hasImage && !uploading && (
              <span className="text-xs text-emerald-600 font-semibold flex items-center gap-1">
                <svg className="h-3.5 w-3.5" viewBox="0 0 20 20" fill="currentColor">
                  <path
                    fillRule="evenodd"
                    d="M16.707 5.293a1 1 0 010 1.414l-8 8a1 1 0 01-1.414 0l-4-4a1 1 0 011.414-1.414L8 12.586l7.293-7.293a1 1 0 011.414 0z"
                    clipRule="evenodd"
                  />
                </svg>
                {t.selectedFile}
              </span>
            )}
          </label>
        ) : null}

        <input
          id={inputId}
          ref={fileInputRef}
          type="file"
          accept={accept}
          disabled={disabled || uploading}
          onChange={handleFileChange}
          className="hidden"
        />

        {!hasImage ? (
          <div
            onDragOver={handleDragOver}
            onDragLeave={handleDragLeave}
            onDrop={handleDrop}
            onClick={() => !disabled && !uploading && fileInputRef.current?.click()}
            className={`relative flex flex-col items-center justify-center rounded-2xl border-2 border-dashed p-6 text-center cursor-pointer transition ${
              isDragging
                ? "border-[var(--primary,#1f6fa8)] bg-[var(--primary,#1f6fa8)]/10 scale-[1.01]"
                : "border-[var(--line,#cbd5e1)] bg-[var(--card,#ffffff)] hover:border-[var(--primary,#1f6fa8)]/60 hover:bg-[#f0f7fc]/50"
            } ${disabled ? "opacity-60 cursor-not-allowed" : ""}`}
          >
            <div className="flex h-12 w-12 items-center justify-center rounded-full bg-[#e0f2fe] text-[#0284c7] transition group-hover:scale-105">
              <svg className="h-6 w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={2}>
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M4 16l4.586-4.586a2 2 0 012.828 0L16 16m-2-2l1.586-1.586a2 2 0 012.828 0L20 14m-6-6h.01M6 20h12a2 2 0 002-2V6a2 2 0 00-2-2H6a2 2 0 00-2 2v12a2 2 0 002 2z"
                />
              </svg>
            </div>
            <p className="mt-3 text-sm font-semibold text-[#0f172a]">{t.dragText}</p>
            <p className="mt-1 text-xs text-[#64748b]">{t.subText}</p>
          </div>
        ) : (
          <div className="relative flex flex-col sm:flex-row items-center gap-4 rounded-2xl border border-[var(--line,#cbd5e1)] bg-[var(--card,#ffffff)] p-3.5 shadow-sm">
            <div className="relative h-20 w-20 shrink-0 overflow-hidden rounded-xl border border-[#e2e8f0] bg-[#f8fafc]">
              <Image
                src={displayUrl}
                alt="Uploaded preview"
                fill
                sizes="80px"
                unoptimized
                className="h-full w-full object-cover"
              />
            </div>

            <div className="min-w-0 flex-1 text-center sm:text-left">
              <p className="truncate text-sm font-semibold text-[#0f172a]" title={selectedFileName || value}>
                {selectedFileName || value.split("/").pop() || t.selectedFile}
              </p>
              {selectedFileSize ? (
                <p className="mt-0.5 text-xs text-[#64748b]">{formatFileSize(selectedFileSize)}</p>
              ) : null}

              <div className="mt-2.5 flex items-center justify-center sm:justify-start gap-3">
                <button
                  type="button"
                  disabled={uploading}
                  onClick={() => fileInputRef.current?.click()}
                  className="text-xs font-semibold text-[#1f6fa8] hover:underline disabled:opacity-50"
                >
                  {t.changePhoto}
                </button>
                <span className="text-gray-300">•</span>
                <button
                  type="button"
                  disabled={uploading}
                  onClick={handleRemove}
                  className="text-xs font-semibold text-rose-600 hover:underline disabled:opacity-50"
                >
                  {t.removePhoto}
                </button>
              </div>
            </div>
          </div>
        )}

        {uploading ? (
          <div className="flex items-center gap-2 rounded-xl bg-[#e0f2fe] px-3.5 py-2.5 text-xs font-medium text-[#0369a1] animate-pulse">
            <div className="h-4 w-4 animate-spin rounded-full border-2 border-[#0284c7] border-t-transparent shrink-0" />
            <span>{uploadProgress || t.uploading}</span>
          </div>
        ) : null}

        {error ? (
          <div className="rounded-xl bg-[#fef2f2] border border-[#fecaca] p-3 text-xs font-medium text-[#b91c1c]">
            {error}
          </div>
        ) : null}

        {helpText ? <p className="text-xs text-[#64748b]">{helpText}</p> : null}
      </div>
    );
  }

  // -------------------------------------------------------------
  // RENDER: Admin / Compact Variant
  // -------------------------------------------------------------
  return (
    <div className={`space-y-2 ${className}`}>
      {label ? (
        <label
          htmlFor={inputId}
          className="block text-xs font-semibold uppercase tracking-wider text-[#475569]"
        >
          {label}
          {required ? <span className="ml-1 text-red-500">*</span> : null}
        </label>
      ) : null}

      <div className="rounded-xl border border-[#cbd5e1] bg-[#f8fafc] p-2.5 sm:p-3 transition hover:border-[#94a3b8]">
        {hasImage ? (
          <div className="space-y-3">
            <div className="relative flex flex-col sm:flex-row sm:items-center gap-3 sm:gap-4">
              <div className="relative h-20 w-20 shrink-0 overflow-hidden rounded-lg border border-[#e2e8f0] bg-white shadow-sm self-center sm:self-auto">
                {/* eslint-disable-next-line @next/next/no-img-element */}
                <img
                  src={displayUrl}
                  alt="Uploaded preview"
                  className="h-full w-full object-cover"
                  onError={(e) => {
                    (e.target as HTMLImageElement).src =
                      "https://via.placeholder.com/150?text=No+Image";
                  }}
                />
              </div>

              <div className="flex-1 min-w-0">
                <p className="text-xs font-medium text-[#1e293b] truncate" title={value || selectedFileName}>
                  {value || selectedFileName}
                </p>
                {selectedFileSize ? (
                  <p className="text-[11px] text-[#64748b] mt-0.5">
                    {formatFileSize(selectedFileSize)}
                  </p>
                ) : null}
                <div className="mt-2 flex flex-wrap gap-2">
                  <button
                    type="button"
                    onClick={() => fileInputRef.current?.click()}
                    disabled={uploading || disabled}
                    className="inline-flex items-center gap-1 rounded-md bg-[#1f6fa8] px-2.5 py-1.5 text-xs font-semibold text-white shadow-sm hover:bg-[#185887] transition disabled:opacity-50"
                  >
                    <svg className="h-3.5 w-3.5" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                      <path
                        strokeLinecap="round"
                        strokeLinejoin="round"
                        d="M4 16v1a3 3 0 003 3h10a3 3 0 003-3v-1m-4-8l-4-4m0 0L8 8m4-4v12"
                      />
                    </svg>
                    {t.changePhoto}
                  </button>

                  {value ? (
                    <button
                      type="button"
                      onClick={handleCopyUrl}
                      className="inline-flex items-center gap-1 rounded-md border border-[#cbd5e1] bg-white px-2.5 py-1.5 text-xs font-medium text-[#334155] hover:bg-[#f1f5f9] transition"
                    >
                      <svg className="h-3.5 w-3.5 text-[#64748b]" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                        <path
                          strokeLinecap="round"
                          strokeLinejoin="round"
                          d="M8 16H6a2 2 0 01-2-2V6a2 2 0 012-2h8a2 2 0 012 2v2m-6 12h8a2 2 0 002-2v-8a2 2 0 00-2-2h-8a2 2 0 00-2 2v8a2 2 0 002 2z"
                        />
                      </svg>
                      {copied ? t.copiedUrl : t.copyUrl}
                    </button>
                  ) : null}

                  <button
                    type="button"
                    onClick={handleRemove}
                    disabled={uploading}
                    className="inline-flex items-center gap-1 rounded-md border border-[#fecaca] bg-white px-2 py-1.5 text-xs font-medium text-[#dc2626] hover:bg-[#fef2f2] transition disabled:opacity-50"
                  >
                    {t.removePhoto}
                  </button>
                </div>
              </div>
            </div>
          </div>
        ) : (
          <div
            onDragOver={handleDragOver}
            onDragLeave={handleDragLeave}
            onDrop={handleDrop}
            onClick={() => !disabled && !uploading && fileInputRef.current?.click()}
            className={`flex cursor-pointer flex-col items-center justify-center rounded-lg border-2 border-dashed border-[#cbd5e1] bg-white py-3.5 px-4 text-center transition hover:border-[#1f6fa8] hover:bg-[#f0f7fc] ${
              isDragging ? "border-[#1f6fa8] bg-[#f0f7fc]" : ""
            } ${disabled ? "opacity-60 cursor-not-allowed" : ""}`}
          >
            <div className="rounded-full bg-[#e0f2fe] p-2.5 text-[#1f6fa8]">
              <svg className="h-5 w-5 sm:h-6 sm:w-6" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth="2">
                <path
                  strokeLinecap="round"
                  strokeLinejoin="round"
                  d="M4 16l4.586-4.586a2 2 0 012.828 0L16 16m-2-2l1.586-1.586a2 2 0 012.828 0L20 14m-6-6h.01M6 20h12a2 2 0 002-2V6a2 2 0 00-2-2H6a2 2 0 00-2 2v12a2 2 0 002 2z"
                />
              </svg>
            </div>
            <p className="mt-1.5 text-xs sm:text-sm font-semibold text-[#0f172a]">
              {t.dragText}
            </p>
            <p className="mt-0.5 text-[11px] text-[#64748b]">
              {t.subText}
            </p>
          </div>
        )}

        <input
          id={inputId}
          ref={fileInputRef}
          type="file"
          accept={accept}
          disabled={disabled || uploading}
          onChange={handleFileChange}
          className="hidden"
        />

        {uploading ? (
          <div className="mt-3 flex items-center gap-2 rounded-lg bg-[#e0f2fe] px-3 py-2 text-xs font-medium text-[#0369a1]">
            <div className="h-3.5 w-3.5 animate-spin rounded-full border-2 border-[#0284c7] border-t-transparent shrink-0" />
            <span>{uploadProgress || t.uploading}</span>
          </div>
        ) : null}

        {error ? (
          <div className="mt-3 rounded-lg bg-[#fef2f2] px-3 py-2 text-xs font-medium text-[#b91c1c]">
            {error}
          </div>
        ) : null}

        <div className="mt-3">
          <label className="text-[11px] font-medium text-[#64748b]">
            {t.urlLabel}
          </label>
          <input
            type="url"
            value={value || ""}
            placeholder="https://... or /uploads/..."
            disabled
            aria-label={`${label || "Uploaded"} URL`}
            className="mt-1 w-full cursor-not-allowed rounded-md border border-[#cbd5e1] bg-[#f1f5f9] px-3 py-1.5 text-xs text-[#64748b] focus:outline-none disabled:opacity-100 font-mono"
          />
        </div>
      </div>

      {helpText ? <p className="text-[11px] text-[#64748b]">{helpText}</p> : null}
    </div>
  );
}
