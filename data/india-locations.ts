export function getDistrictsForState(stateName?: string): string[] {
  if (!stateName || !stateName.trim()) {
    // Return all unique districts across India sorted alphabetically
    const allSet = new Set<string>();
    Object.values(INDIAN_DISTRICTS_BY_STATE).forEach((list) => {
      list.forEach((d) => allSet.add(d));
    });
    return Array.from(allSet).sort((a, b) => a.localeCompare(b));
  }

  const normalized = stateName.trim();
  const directMatch = INDIAN_DISTRICTS_BY_STATE[normalized];
  if (directMatch) return directMatch;

  // Case-insensitive fallback match
  const foundKey = Object.keys(INDIAN_DISTRICTS_BY_STATE).find(
    (k) => k.toLowerCase() === normalized.toLowerCase(),
  );
  if (foundKey) return INDIAN_DISTRICTS_BY_STATE[foundKey];

  // Return all districts if custom state typed
  const allSet = new Set<string>();
  Object.values(INDIAN_DISTRICTS_BY_STATE).forEach((list) => {
    list.forEach((d) => allSet.add(d));
  });
  return Array.from(allSet).sort((a, b) => a.localeCompare(b));
}
